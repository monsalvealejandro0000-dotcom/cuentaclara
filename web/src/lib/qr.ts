/**
 * Código QR (ISO/IEC 18004) para la verificación en dos pasos (fase 13), hecho aquí para no depender de nadie:
 * la clave secreta se dibuja en el navegador y nunca sale a ningún servicio.
 *
 * Solo lo necesario: modo byte (UTF-8), corrección de errores M (≈15 %), versiones 1 a 40 y la máscara con
 * menos penalización. Sin importaciones: las pruebas (tests/account.test.js) lo cargan directamente con Node.
 */

export type QrCode = { size: number; modules: boolean[][]; version: number; mask: number };

/** Nivel de corrección: índice en las tablas (0 = L, 1 = M, 2 = Q, 3 = H) y sus 2 bits en la información de formato. */
const ECL = { L: 0, M: 1, Q: 2, H: 3 } as const;
type Ecl = (typeof ECL)[keyof typeof ECL];
const ECL_FORMAT_BITS = [1, 0, 3, 2];

// Códigos de corrección por bloque y número de bloques, por nivel y versión (tablas 9 de la norma). Índice 0 sin usar.
// prettier-ignore
